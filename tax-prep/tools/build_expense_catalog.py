"""Generate js/expense-catalog.js: every organizer expense field with its
label, Schedule C line and deductible share, plus the car fields. Used by the
Preparer summary to itemize Schedule C from a fillable-PDF or scanned organizer.

Run after changing EXPENSES / CAR_* in build_organizer.py:
    python3 tax-prep/tools/build_expense_catalog.py
"""
import json
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from build_organizer import CAR_COSTS, CAR_MILES, EXPENSES  # noqa: E402
from build_organizer_pdf import expense_field  # noqa: E402
from pypdf import PdfReader  # noqa: E402

PDF = "tax-prep/downloads/falcon-tax-organizer-2026.pdf"
OUT = "tax-prep/js/expense-catalog.js"

seen = {}
fields = {}
group = ""
for label, line, share, _tip in EXPENSES:
    if line is None:
        group = label
        continue
    name = expense_field(label, share, seen)
    fields[name] = {"label": label or "Other expense", "line": line, "share": share, "group": group}
car = {f"car_{k}": lab for k, lab in CAR_COSTS}
miles = {f"car_{k}": lab for k, lab in CAR_MILES}

# every generated name must exist in the fillable PDF
pdf_names = set(PdfReader(PDF).get_fields())
missing = [n for n in list(fields) + list(car) + list(miles) if n not in pdf_names]
assert not missing, f"not in the PDF: {missing}"

js = ("// Generated by tools/build_expense_catalog.py from build_organizer.py. Do not edit.\n"
      "(function (root) {\n"
      f"  const api = {{ expenses: {json.dumps(fields)},\n    car: {json.dumps(car)},\n    miles: {json.dumps(miles)} }};\n"
      "  if (typeof module !== 'undefined' && module.exports) module.exports = api;\n"
      "  else root.ExpenseCatalog = api;\n"
      "})(typeof window !== 'undefined' ? window : globalThis);\n")
open(OUT, "w").write(js)
print(len(fields), "expense fields,", len(car), "car cost fields ->", OUT)
