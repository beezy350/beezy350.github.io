"""Generate scan-reader/fields.js from the fillable PDF organizer's form fields.

Run after rebuilding downloads/falcon-tax-organizer-2026.pdf:
    python3 tax-prep/tools/build_scan_fields.py
"""
import json
from pypdf import PdfReader

SRC = "tax-prep/downloads/falcon-tax-organizer-2026.pdf"
OUT = "tax-prep/scan-reader/fields.js"
FIX = {"status_single": "Filing status: Single", "status_mfj": "Filing status: Married filing jointly",
       "status_mfs": "Filing status: Married filing separately", "status_hoh": "Filing status: Head of household",
       "state": "State lived in during 2026", "birth_you": "Your birth year", "birth_spouse": "Spouse's birth year",
       "childcare": "Paid childcare so I could work"}

fields = []
for page_no, page in enumerate(PdfReader(SRC).pages, 1):
    for a in page.get("/Annots", []):
        o = a.get_object()
        name = o.get("/T")
        if not name or name.startswith("contact_") or name == "consent":
            continue  # contact details are never sent for reading
        label = FIX.get(name, str(o.get("/TU", "")))
        if name.startswith("exp_"):
            label = "Expense: " + (label or "Other")
        if name.startswith("chk_"):
            label = "Checklist: " + label
        fields.append({"name": str(name), "label": label, "page": page_no,
                       "kind": "check" if o.get("/FT") == "/Btn" else "text"})

with open(OUT, "w") as f:
    f.write("// Generated by tools/build_scan_fields.py from downloads/falcon-tax-organizer-2026.pdf.\n"
            "// Contact and consent fields are left out. Field names match js/organizer-map.js.\n"
            "window.ORGANIZER_FIELDS = " + json.dumps(fields, indent=0) + ";\n")
print(len(fields), "fields ->", OUT)
